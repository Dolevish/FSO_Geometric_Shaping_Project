function report=test_commit_o_m8_snr30_preflight()
%TEST_COMMIT_O_M8_SNR30_PREFLIGHT  Structural tests; no expensive AMI runs.
    P=run_commit_o_m8_snr30('DryRun',true);
    assert(P.dryRun && P.config.M==8 && P.config.SNRdB==30 && ...
        abs(P.config.SigmaR2-0.3)<eps && ...
        P.config.nStarts==12 && P.config.SAIterations==4000 && ...
        P.config.GPSMaxEvals==4001 && ...
        P.config.GPSOptions.UseCompletePoll && ...
        P.config.GPSControlOptions.UseCompletePoll && ...
        P.config.GPSOptions.MeshTolerance==1e-7 && ...
        P.config.GPSControlOptions.MeshTolerance==1e-6 && ...
        height(P.taskPlan)==36);
    cfg=build_fso_config(8,1,30,0.3,'minGap',0.01,'pinZero',true);
    for k=1:12
        x=AMI_functions.project_constellation_1D(P.rawStarts(:,k),cfg);
        assert(norm(x-P.feasibleStarts(:,k),inf)<1e-12);
        for j=k+1:12
            assert(norm(P.feasibleStarts(:,k)-P.feasibleStarts(:,j),inf)>1e-10);
        end
    end
    assert(isequal(P.taskPlan.Restart,repmat((1:12)',3,1)) && ...
        all(P.taskPlan.Method(1:12)=="SA") && ...
        all(P.taskPlan.Method(13:24)=="GPS") && ...
        all(P.taskPlan.Method(25:36)=="GPS_CONTROL"));
    methods=[repmat("GPS",12,1);repmat("SA",12,1); ...
        repmat("GPS_CONTROL",12,1)];
    synthetic=table(methods,repmat((1:12)',3,1), ...
        repmat((1:12)'*0.01,3,1),ones(36,1)*4001, ...
        'VariableNames',{'Method','Restart','ValidatedAMI','FunctionEvaluations'});
    S=commit_o_optimizer_statistics(synthetic);
    assert(height(S)==3 && all(S.N==12) && ...
        all(abs(S.BestValidatedAMI-0.12)<1e-12) && ...
        all(abs(S.MeanValidatedAMI-0.065)<1e-12) && ...
        all(abs(S.StdValidatedAMI-std((1:12)'*0.01,0))<1e-12));
    report=struct('passed',true,'M',8,'SNRdB',30, ...
        'nRestartsPerArm',12,'nArms',3,'nDistinctStarts',12, ...
        'GPSMeshTolerance',1e-7,'ControlMeshTolerance',1e-6, ...
        'figureUses','maximum validated AMI, no error bars', ...
        'durationFormat','MMm SS.SSs');
    disp(report);
end
