function report=test_commit_p_final_ieee_preflight()
%TEST_COMMIT_P_FINAL_IEEE_PREFLIGHT  Cheap structural checks only.
    t=run_commit_p_final_ieee_fig7('DryRun',true);
    c=t.config;
    assert(t.dryRun && c.M==8 && c.SNRdB==20 && ...
        abs(c.SigmaR2-0.3)<eps && c.nStarts==12 && ...
        c.SAIterations==4000 && c.GPSMaxEvals==4001 && ...
        c.GPSOptions.UseCompletePoll && c.GPSOptions.MeshTolerance==1e-6 && ...
        c.GPSOptions.StepTolerance==1e-8 && ...
        c.GPSOptions.FunctionTolerance==1e-8 && ...
        c.loghDt==0.01 && c.seedOffset==104729 && ...
        c.masterSeed~=c.commitMSeed && height(t.taskPlan)==24);
    cfg=build_fso_config(8,1,20,0.3,'minGap',0.01,'pinZero',true);
    for k=1:12
        x=AMI_functions.project_constellation_1D(t.rawStarts(:,k),cfg);
        assert(norm(x-t.feasibleStarts(:,k),inf)<1e-12);
        for j=k+1:12
            assert(norm(t.feasibleStarts(:,k)-t.feasibleStarts(:,j),inf)>1e-10);
        end
    end
    assert(isequal(t.taskPlan.Restart,repmat((1:12)',2,1)) && ...
        all(t.taskPlan.Method(1:12)=="SA") && ...
        all(t.taskPlan.Method(13:24)=="GPS"));
    toy=table([repmat("GPS",12,1);repmat("SA",12,1)], ...
        repmat((1:12)',2,1),repmat((1:12)'*.01,2,1), ...
        ones(24,1)*4001, ...
        'VariableNames',{'Method','Restart','ValidatedAMI','FunctionEvaluations'});
    a=commit_m_optimizer_statistics(toy);
    assert(height(a)==2 && all(a.N==12) && ...
        all(abs(a.BestValidatedAMI-.12)<1e-12) && ...
        all(abs(a.MeanValidatedAMI-.065)<1e-12) && ...
        all(abs(a.StdValidatedAMI-std((1:12)'*.01,0))<1e-12));
    report=struct('passed',true,'M',8,'SNRdB',20, ...
        'nStarts',12,'nTasks',24,'completePoll',true, ...
        'meshTolerance',1e-6,'masterSeed',c.masterSeed, ...
        'reporting','max validated across 12 + sample stats all 12', ...
        'progressFormat','mm minutes, ss.ss seconds');
    disp(report);
end
