function O = run_commit_o_m8_snr30(varargin)
%RUN_COMMIT_O_M8_SNR30  Paired SA/GPS mesh-tolerance sensitivity experiment.
% 12 unique shared starts; M=8, SNR=30dB, sigma_R^2=0.3.
% Three groups (12 each): SA, GPS (tight mesh 1e-7), GPS_CONTROL (mesh 1e-6).
% Both GPS runs use complete polling and 4001 maximum objective evaluations.
% SA uses 4000 iterations; all other settings match Commits M/N.
% Four-method Figure 7 uses MAXIMUM validated AMI, without error bars.
% Each worker sends START and DONE including elapsed minutes and seconds.
%
%   addpath(genpath(fullfile(pwd,'src')));
%   test_commit_o_m8_snr30_preflight();
%   plan = run_commit_o_m8_snr30('DryRun',true);
%   O = run_commit_o_m8_snr30();

    p=inputParser; p.FunctionName=mfilename;
    addParameter(p,'M8ResultPath','',@is_text);
    addParameter(p,'M16ResultPath','',@is_text);
    addParameter(p,'ResumeDirectory','',@is_text);
    addParameter(p,'UseParallel',true,@is_bool);
    addParameter(p,'ParallelWorkers',8,@positive_int);
    addParameter(p,'DryRun',false,@is_bool);
    parse(p,varargin{:}); o=p.Results;
    P=i11p1_production_config();
    F=i13d_benchmark_config();
    F.PatternSearch.UseCompletePoll=true;
    controlGPS=F.PatternSearch;
    F.PatternSearch.MeshTolerance=1e-7;
    assert(abs(controlGPS.MeshTolerance-1e-6)<eps && ...
        abs(F.PatternSearch.MeshTolerance-1e-7)<eps, ...
        'CommitO:MeshDefaults','GPS mesh tolerance policy was unexpectedly modified.');
    m=8; snr=30; sigmaR2=0.3; nStarts=12; nTasks=3*nStarts;
    nSAIterations=4000; maxGPSEvals=nSAIterations+1;
    [loghDt,dtMeta]=select_logh_dt(m,snr,sigmaR2, ...
        'Policy',P.LoghDtPolicy,'BaseDt',P.loghDt, ...
        'RefinedDt',P.loghDtRefined);
    assert(loghDt==0.01 && F.MaxEvalsPerStart(F.MVec==m)==maxGPSEvals && ...
        P.P_avg==1 && P.minGap==0.01 && P.pinZero && ...
        P.T0==0.4 && P.Tf==1e-3 && P.BaseStd0==0.15 && ...
        P.ItersPerTemp==50 && strcmp(P.FastFadingMethod,'logh') && ...
        strcmp(P.YGridMode,'candidate-adaptive') && P.YGridScale==1.1 && ...
        P.loghSpanSigma==8 && P.loghYBlockSize==512 && ...
        F.PatternSearch.UseCompletePoll && ~F.PatternSearch.UseParallel, ...
        'CommitO:FrozenConfig','The scientific conditions differ from Commit M.');
    cfg=build_fso_config(m,P.P_avg,snr,sigmaR2, ...
        'FastFadingMethod',P.FastFadingMethod,'loghDt',loghDt, ...
        'loghSpanSigma',P.loghSpanSigma, ...
        'loghYBlockSize',P.loghYBlockSize, ...
        'YGridMode',P.YGridMode,'YGridScale',P.YGridScale, ...
        'minGap',P.minGap,'pinZero',P.pinZero, ...
        'saMaxIter',nSAIterations,'saNStarts',nStarts, ...
        'seedInit',0,'logEvery',0,'historyEvery',P.historyEvery);
    cfg.SA.T0=P.T0;cfg.SA.Tf=P.Tf;
    cfg.SA.baseStd0=P.BaseStd0;cfg.SA.itersPerTemp=P.ItersPerTemp;
    cfg.SA.nBlocks=ceil(cfg.SA.maxIter/cfg.SA.itersPerTemp);
    cfg.SA.coolingRate=exp(log(cfg.SA.Tf/cfg.SA.T0)/cfg.SA.nBlocks);

    uniform=define_constellation(m,P.P_avg,true,"mean");
    masterSeed=fso_result_utils.case_seed(P.baseSeed,m,snr,sigmaR2);
    Xraw=i13_shared_start_points(cfg,uniform,masterSeed,nStarts);
    Xfeasible=zeros(m,nStarts);
    for k=1:nStarts
        Xfeasible(:,k)=AMI_functions.project_constellation_1D(Xraw(:,k),cfg);
        AMI_functions.assert_constellation_feasible(Xfeasible(:,k),cfg,1e-10);
    end
    assert(norm(Xfeasible(:,1)-uniform(:),inf)<1e-12, ...
        'CommitO:FirstStart','First restart must be uniform PAM.');
    for k=1:nStarts
        for j=k+1:nStarts
            assert(norm(Xfeasible(:,k)-Xfeasible(:,j),inf)>1e-10, ...
                'CommitO:DuplicateStart','Restart starting points must be distinct.');
        end
    end
    taskMethod=[repmat("SA",nStarts,1);repmat("GPS",nStarts,1); ...
        repmat("GPS_CONTROL",nStarts,1)];
    taskRestart=repmat((1:nStarts)',3,1);
    taskPlan=table(taskMethod,taskRestart,'VariableNames',{'Method','Restart'});
    frozen=struct('version','CommitO-v1','M',m,'SNRdB',snr, ...
        'SigmaR2',sigmaR2,'Pavg',P.P_avg,'minGap',P.minGap, ...
        'nStarts',nStarts,'masterSeed',masterSeed, ...
        'SAIterations',nSAIterations,'GPSMaxEvals',maxGPSEvals, ...
        'saT0',P.T0,'saTf',P.Tf,'saBaseStd0',P.BaseStd0, ...
        'saItersPerTemp',P.ItersPerTemp,'dtMeta',dtMeta, ...
        'loghDt',loghDt,'loghSpanSigma',P.loghSpanSigma, ...
        'YGridMode',P.YGridMode,'YGridScale',P.YGridScale, ...
        'loghYBlockSize',P.loghYBlockSize, ...
        'GPSOptions',F.PatternSearch,'GPSControlOptions',controlGPS, ...
        'ZhouExtraBits',2, ...
        'startPolicy','uniform first, 11 Threefry gaussian 0.2, shared SA/GPS');
    signature=char(jsonencode(frozen));

    if o.DryRun
        O=struct('dryRun',true,'config',frozen,'taskPlan',taskPlan, ...
            'rawStarts',Xraw,'feasibleStarts',Xfeasible);
        fprintf('Commit O DRY RUN: M=8 SNR=30 dB, 12 shared starts, 36 restarts, two GPS mesh settings.\n');
        return;
    end

    % Previous Commit M and N results are read-only cross-case references.
    m8Path=find_m8(o.M8ResultPath);
    A8=load(m8Path,'M');
    assert(isfield(A8,'M') && isfield(A8.M,'signature') && ...
        isfield(A8.M,'optimizerStats') && isfield(A8.M,'fourMethodTable') && ...
        A8.M.signature.M==8 && A8.M.signature.SNRdB==20 && ...
        abs(A8.M.signature.SigmaR2-sigmaR2)<1e-12 && ...
        A8.M.signature.PatternSearch.UseCompletePoll && ...
        A8.M.signature.nStarts==12, ...
        'CommitO:CommitM','Expected valid M8/SNR20 Commit M results.');
    m16Path=find_m16(o.M16ResultPath);
    A16=load(m16Path,'N');
    assert(isfield(A16,'N') && isfield(A16.N,'config') && ...
        isfield(A16.N,'optimizerStats') && isfield(A16.N,'fourMethodTable') && ...
        A16.N.config.M==16 && A16.N.config.SNRdB==20 && ...
        abs(A16.N.config.SigmaR2-sigmaR2)<1e-12 && ...
        A16.N.config.GPSOptions.UseCompletePoll && ...
        A16.N.config.nStarts==12, ...
        'CommitO:CommitN','Expected valid M16/SNR20 Commit N results.');

    % Independently evaluate BOTH baselines for the new M=16 constellation.
    fprintf('[CommitO|M8|SNR30|Uniform PAM] START\n');
    t=tic; uniformMI=cfg.AMI_Validator(uniform(:));
    fprintf('[CommitO|M8|SNR30|Uniform PAM] DONE | AMI=%.9f | elapsed=%s\n',uniformMI,mmss(toc(t)));
    fprintf('[CommitO|M8|SNR30|Zhou GS] START\n');
    t=tic;
    zhou=zhou2025_optical_gs_constellation(m,P.P_avg, ...
        'ExtraBits',2,'Regularize',true);
    AMI_functions.assert_constellation_feasible(zhou.x,cfg,1e-10);
    zhouMI=cfg.AMI_Validator(zhou.x);
    fprintf('[CommitO|M8|SNR30|Zhou GS] DONE | AMI=%.9f | elapsed=%s\n',zhouMI,mmss(toc(t)));
    assert(all(isfinite([uniformMI,zhouMI])) && ...
        all([uniformMI,zhouMI]>=0) && all([uniformMI,zhouMI]<=log2(m)+1e-6), ...
        'CommitO:BadBaselines','Invalid baseline AMI.');

    outputRoot=fullfile(fso_result_utils.revision2_results_root(),'commit_o_m8_snr30');
    if strlength(string(o.ResumeDirectory))>0
        outDir=char(o.ResumeDirectory);
        assert(isfolder(outDir),'CommitO:BadResume','ResumeDirectory does not exist.');
    else
        stamp=char(datetime('now','TimeZone','UTC','Format','yyyyMMdd_HHmmss_SSS'));
        outDir=fullfile(outputRoot,['O_' stamp]);
        if ~isfolder(outDir),mkdir(outDir);end
    end
    cpDir=fullfile(outDir,'checkpoints');
    gpsDir=fullfile(outDir,'native_gps');
    if ~isfolder(cpDir),mkdir(cpDir);end
    if ~isfolder(gpsDir),mkdir(gpsDir);end

    results=cell(nTasks,1); cp=cell(nTasks,1);
    for k=1:nTasks
        key=sprintf('%s_restart_%02d',char(taskMethod(k)),taskRestart(k));
        cp{k}=fullfile(cpDir,[key '.mat']);
        if isfile(cp{k})
            L=load(cp{k},'checkpoint');
            assert(isfield(L,'checkpoint') && ...
                strcmp(L.checkpoint.signature,signature) && ...
                strcmp(L.checkpoint.key,key), ...
                'CommitO:Checkpoint','Checkpoint science/identity mismatch: %s',cp{k});
            results{k}=L.checkpoint.result;
            audit_one(results{k},taskMethod(k),taskRestart(k), ...
                Xfeasible(:,taskRestart(k)),cfg,maxGPSEvals);
            fprintf('[CommitO|M8|SNR30|%s|restart %02d] RESUMED | validated=%.9f | elapsed=%s\n', ...
                char(taskMethod(k)),taskRestart(k),results{k}.validatedAMI,mmss(results{k}.runtimeSeconds));
        end
    end

    pending=find(cellfun(@isempty,results));
    fprintf('Commit O: %d/36 completed, %d pending | %s\n',nTasks-numel(pending),numel(pending),outDir);
    if ~isempty(pending)
        progress=parallel.pool.DataQueue;
        afterEach(progress,@(message) fprintf('%s\n',message));
        if o.UseParallel
            pool=gcp('nocreate');
            if isempty(pool) || pool.NumWorkers~=o.ParallelWorkers
                if ~isempty(pool),delete(pool);end
                pool=parpool('Processes',double(o.ParallelWorkers));
            end
            active=parallel.FevalFuture.empty(0,1);
            activeRows=zeros(0,1);
            next=1;
            while numel(active)<pool.NumWorkers && next<=numel(pending)
                row=pending(next);
                active(end+1,1)=parfeval(pool,@run_one,1, ...
                    taskMethod(row),taskRestart(row),cfg,uniform,masterSeed, ...
                    maxGPSEvals,F.PatternSearch,signature,cp{row},gpsDir,progress);
                activeRows(end+1,1)=row;
                next=next+1;
            end
            try
                while ~isempty(active)
                    [finished,r]=fetchNext(active);
                    row=activeRows(finished);
                    active(finished)=[];
                    activeRows(finished)=[];
                    audit_one(r,taskMethod(row),taskRestart(row), ...
                        Xfeasible(:,taskRestart(row)),cfg,maxGPSEvals);
                    results{row}=r;
                    fprintf('[CommitO|M8|SNR30] Progress: %d/%d restarts completed\n', ...
                        nnz(~cellfun(@isempty,results)),nTasks);
                    if next<=numel(pending)
                        newer=pending(next);
                        active(end+1,1)=parfeval(pool,@run_one,1, ...
                            taskMethod(newer),taskRestart(newer),cfg,uniform,masterSeed, ...
                            maxGPSEvals,F.PatternSearch,signature,cp{newer},gpsDir,progress);
                        activeRows(end+1,1)=newer;
                        next=next+1;
                    end
                end
            catch ME
                if ~isempty(active),cancel(active);end
                rethrow(ME);
            end
        else
            for ii=1:numel(pending)
                row=pending(ii);
                results{row}=run_one(taskMethod(row),taskRestart(row), ...
                    cfg,uniform,masterSeed,maxGPSEvals,F.PatternSearch, ...
                    signature,cp{row},gpsDir,progress);
                audit_one(results{row},taskMethod(row),taskRestart(row), ...
                    Xfeasible(:,taskRestart(row)),cfg,maxGPSEvals);
            end
        end
    end

    assert(all(~cellfun(@isempty,results)),'CommitO:Incomplete','36 validated tasks are required.');
    Method=strings(nTasks,1);Restart=zeros(nTasks,1);
    ValidatedAMI=zeros(nTasks,1);FastAMI=zeros(nTasks,1);
    FunctionEvaluations=zeros(nTasks,1);Iterations=zeros(nTasks,1);
    Exitflag=nan(nTasks,1);RuntimeSeconds=zeros(nTasks,1);
    FinalMeshSize=nan(nTasks,1);MeshTolerance=nan(nTasks,1);
    StartLevels=strings(nTasks,1);BestLevels=strings(nTasks,1);
    for k=1:nTasks
        r=results{k};Method(k)=r.method;Restart(k)=r.restart;
        ValidatedAMI(k)=r.validatedAMI;FastAMI(k)=r.fastAMI;
        FunctionEvaluations(k)=r.functionEvaluations;
        Iterations(k)=r.iterations;Exitflag(k)=r.exitflag;
        RuntimeSeconds(k)=r.runtimeSeconds;
        if r.method=="GPS" || r.method=="GPS_CONTROL"
            FinalMeshSize(k)=r.details.finalMeshSize;
            if r.method=="GPS"
                MeshTolerance(k)=F.PatternSearch.MeshTolerance;
            else
                MeshTolerance(k)=controlGPS.MeshTolerance;
            end
        end
        StartLevels(k)=string(mat2str(r.startFeasible(:).',12));
        BestLevels(k)=string(mat2str(r.xBest(:).',12));
    end
    restartTable=table(Method,Restart,ValidatedAMI,FastAMI, ...
        FunctionEvaluations,Iterations,Exitflag,RuntimeSeconds, ...
        FinalMeshSize,MeshTolerance,StartLevels,BestLevels);
    stats=commit_o_optimizer_statistics(restartTable);
    gpsMax=stats.BestValidatedAMI(stats.Method=="GPS");
    saMax=stats.BestValidatedAMI(stats.Method=="SA");

    methods=["Uniform PAM";"Zhou GS";"Pattern Search";"SA"];
    four=table(methods,[uniformMI;zhouMI;gpsMax;saMax], ...
        'VariableNames',{'Method','ValidatedAMI'});
    % Full historical four-method comparison (different M and/or SNR).
    methodsExpected=["Uniform PAM";"Zhou GS";"Pattern Search";"SA"];
    T8=A8.M.fourMethodTable;T16=A16.N.fourMethodTable;
    assert(isequal(string(T8.Method(:)),methodsExpected) && ...
        isequal(string(T16.Method(:)),methodsExpected) && ...
        isequal(string(four.Method(:)),methodsExpected), ...
        'CommitO:PriorMethods','Prior four-method orders differ.');
    scoreM=double(T8.ValidatedAMI(:));
    scoreN=double(T16.ValidatedAMI(:));
    scoreO=double(four.ValidatedAMI(:));
    comparison=table(methodsExpected,scoreM,scoreN,scoreO, ...
        scoreM/log2(8),scoreN/log2(16),scoreO/log2(8), ...
        'VariableNames',{'Method','CommitM_M8_SNR20','CommitN_M16_SNR20', ...
        'CommitO_M8_SNR30','NormalizedCommitM', ...
        'NormalizedCommitN','NormalizedCommitO'});
    S8=A8.M.optimizerStats;S16=A16.N.optimizerStats;
    assert(isequal(string(S8.Method(:)),["GPS";"SA"]) && ...
        isequal(string(S16.Method(:)),["GPS";"SA"]), ...
        'CommitO:PriorStats','Prior optimizer statistics are incompatible.');
    SO=stats(ismember(stats.Method,["GPS","SA"]),:);
    assert(isequal(string(SO.Method(:)),["GPS";"SA"]), ...
        'CommitO:NewStats','New optimizer statistics are reordered.');
    optimizerComparison=table(string(SO.Method), ...
        S8.BestValidatedAMI,S16.BestValidatedAMI,SO.BestValidatedAMI, ...
        S8.MeanValidatedAMI,S16.MeanValidatedAMI,SO.MeanValidatedAMI, ...
        S8.StdValidatedAMI,S16.StdValidatedAMI,SO.StdValidatedAMI, ...
        'VariableNames',{'Method','CommitMMax','CommitNMax','CommitOMax', ...
        'CommitMMean','CommitNMean','CommitOMean', ...
        'CommitMStd','CommitNStd','CommitOStd'});

    % Tight-vs-control paired GPS analysis, holding EVERYTHING except MeshTolerance.
    tight=sortrows(restartTable(restartTable.Method=="GPS",:),'Restart');
    control=sortrows(restartTable(restartTable.Method=="GPS_CONTROL",:),'Restart');
    assert(height(tight)==12 && height(control)==12 && ...
        isequal(tight.Restart,control.Restart) && ...
        all(abs(tight.MeshTolerance-1e-7)<eps) && ...
        all(abs(control.MeshTolerance-1e-6)<eps) && ...
        isequal(tight.StartLevels,control.StartLevels), ...
        'CommitO:ControlPairing','GPS sensitivity pairs/settings do not match.');
    sensitivity=table(tight.Restart, ...
        control.ValidatedAMI,tight.ValidatedAMI, ...
        tight.ValidatedAMI-control.ValidatedAMI, ...
        control.FunctionEvaluations,tight.FunctionEvaluations, ...
        control.Exitflag,tight.Exitflag, ...
        control.FinalMeshSize,tight.FinalMeshSize, ...
        'VariableNames',{'Restart','ControlAMI','TightAMI', ...
        'TightMinusControlAMI','ControlEvals','TightEvals', ...
        'ControlExitflag','TightExitflag','ControlFinalMesh','TightFinalMesh'});
    sControl=stats(stats.Method=="GPS_CONTROL",:);
    sTight=stats(stats.Method=="GPS",:);
    sensitivitySummary=table(1e-6,1e-7, ...
        sControl.BestValidatedAMI,sTight.BestValidatedAMI, ...
        sTight.BestValidatedAMI-sControl.BestValidatedAMI, ...
        sControl.MeanValidatedAMI,sTight.MeanValidatedAMI, ...
        sControl.StdValidatedAMI,sTight.StdValidatedAMI, ...
        mean(sensitivity.TightMinusControlAMI), ...
        'VariableNames',{'ControlMesh','TightMesh','ControlMaximum', ...
        'TightMaximum','MaximumDelta','ControlMean','TightMean', ...
        'ControlStd','TightStd','PairedMeanDelta'});

    O=struct('version','CommitO-v1','dryRun',false,'config',frozen, ...
        'outputDirectory',outDir,'sourceCommitM',m8Path, ...
        'sourceCommitN',m16Path,'taskPlan',taskPlan, ...
        'rawStarts',Xraw,'feasibleStarts',Xfeasible, ...
        'uniformConstellation',uniform(:),'zhouGS',zhou, ...
        'restartTable',restartTable,'optimizerStats',stats, ...
        'fourMethodTable',four,'historicalComparison',comparison, ...
        'historicalOptimizerComparison',optimizerComparison, ...
        'meshSensitivity',sensitivity,'meshSensitivitySummary',sensitivitySummary, ...
        'results',{results});
    writetable(restartTable,fullfile(outDir,'CommitO_all_36_restarts.csv'));
    writetable(stats,fullfile(outDir,'CommitO_optimizer_stats_12_restarts.csv'));
    writetable(four,fullfile(outDir,'Fig7_CommitO_four_methods.csv'));
    writetable(sensitivity,fullfile(outDir,'CommitO_GPS_mesh_12_pairs.csv'));
    writetable(sensitivitySummary,fullfile(outDir,'CommitO_GPS_mesh_summary.csv'));
    writetable(comparison,fullfile(outDir,'CommitO_M_N_O_four_methods.csv'));
    writetable(optimizerComparison,fullfile(outDir,'CommitO_M_N_O_optimizer_stats.csv'));
    O.figurePaths=plot_commit_o_m8_snr30_fig7(four,outDir);
    save(fullfile(outDir,'CommitO_results.mat'),'O','-v7.3');
    fprintf('Commit O COMPLETE | GPS tight=%.9f GPS control=%.9f SA=%.9f | SA-GPS=%+.9f\n', ...
        gpsMax,sControl.BestValidatedAMI,saMax,saMax-gpsMax);
    disp(comparison);disp(sensitivitySummary);
    fprintf('All outputs: %s\n',outDir);
end

function r=run_one(method,k,cfg,uniform,seed,maxEvals,policy,signature,cpPath,gpsDir,progress)
    method=string(method);
    timer=tic;
    send(progress,sprintf('[CommitO|M8|SNR30|%s|restart %02d] START',char(method),k));
    try
        if method=="SA"
            a=sa_restart_task(cfg,uniform,seed,k,'[CommitO|SA]');
            r=struct('method',method,'restart',k,'startRaw',a.x0_raw(:), ...
                'startFeasible',a.x0_projected(:),'xBest',a.x_best(:), ...
                'fastAMI',a.bestMIFast,'validatedAMI',a.bestMIValidated, ...
                'functionEvaluations',cfg.SA.maxIter+1, ...
                'iterations',a.nIterations,'exitflag',NaN,'details',a);
        elseif method=="GPS" || method=="GPS_CONTROL"
            if method=="GPS_CONTROL"
                policy.MeshTolerance=1e-6;
            end
            ident=struct('IdentityKey',sprintf('CommitO_%s_r%02d',char(method),k), ...
                'M',cfg.M,'SNRdB',cfg.SNR_dB,'SigmaR2',cfg.sigma_X_sq, ...
                'Replicate',1,'Restart',k,'Seed',double(seed));
            native=fullfile(gpsDir,sprintf('%s_r%02d.mat',char(method),k));
            g=i13d_patternsearch_restart_task(cfg,uniform,seed,k,maxEvals, ...
                policy,ident,native,signature);
            assert(g.success,'CommitO:GPSFailure','%s restart %d: %s', ...
                char(method),k,char(g.errorMessage));
            r=struct('method',method,'restart',k,'startRaw',g.x0Raw(:), ...
                'startFeasible',g.x0Feasible(:),'xBest',g.xBest(:), ...
                'fastAMI',g.bestMIFast,'validatedAMI',g.bestMIValidated, ...
                'functionEvaluations',g.functionEvaluations, ...
                'iterations',g.iterations,'exitflag',g.exitflag,'details',g);
        else
            error('CommitO:Method','Unknown method %s',char(method));
        end
        r.runtimeSeconds=toc(timer);
        key=sprintf('%s_restart_%02d',char(method),k);
        checkpoint=struct('signature',signature,'key',key,'result',r);
        temp=[tempname(fileparts(cpPath)) '.mat'];
        cleanup=onCleanup(@()delete_tmp(temp)); %#ok<NASGU>
        save(temp,'checkpoint','-v7.3');
        [ok,msg]=movefile(temp,cpPath,'f');
        assert(ok,'CommitO:CheckpointSave','%s',msg);
        send(progress,sprintf('[CommitO|M8|SNR30|%s|restart %02d] DONE | elapsed=%s | validated=%.9f | evals=%d', ...
            char(method),k,mmss(r.runtimeSeconds),r.validatedAMI,r.functionEvaluations));
    catch ME
        send(progress,sprintf('[CommitO|M8|SNR30|%s|restart %02d] FAILED | elapsed=%s | %s', ...
            char(method),k,mmss(toc(timer)),ME.message));
        rethrow(ME);
    end
end

function audit_one(r,method,k,x0,cfg,budget)
    assert(string(r.method)==string(method) && r.restart==k && ...
        norm(r.startFeasible(:)-x0(:),inf)<1e-10 && ...
        isfinite(r.validatedAMI) && r.validatedAMI>=0 && ...
        r.validatedAMI<=log2(cfg.M)+1e-6 && ...
        abs(r.fastAMI-r.validatedAMI)<1e-3 && ...
        isfinite(r.functionEvaluations) && ...
        r.functionEvaluations>=1 && r.functionEvaluations<=budget, ...
        'CommitO:ResultAudit','Run result invalid for %s restart %d.',method,k);
    AMI_functions.assert_constellation_feasible(r.xBest,cfg,1e-10);
end

function path=find_m8(provided)
    if strlength(string(provided))>0
        path=char(provided);
        assert(isfile(path),'CommitO:M8Path','Provided M8ResultPath not found.');
        return;
    end
    root=fullfile(fso_result_utils.revision2_results_root(),'commit_m_final_fig7');
    hits=dir(fullfile(root,'**','CommitM_results.mat'));
    assert(~isempty(hits),'CommitO:MissingM8', ...
        'Please pass M8ResultPath pointing to your finished CommitM_results.mat.');
    [~,ii]=max([hits.datenum]);
    path=fullfile(hits(ii).folder,hits(ii).name);
end

function path=find_m16(provided)
    if strlength(string(provided))>0
        path=char(provided);
        assert(isfile(path),'CommitO:MissingM16','Provided M16ResultPath not found.');
        return;
    end
    root=fullfile(fso_result_utils.revision2_results_root(),'commit_n_m16_fig7');
    hits=dir(fullfile(root,'**','CommitN_M16_results.mat'));
    assert(~isempty(hits),'CommitO:MissingM16', ...
        'Pass M16ResultPath for the completed Commit N result.');
    [~,ii]=max([hits.datenum]);
    path=fullfile(hits(ii).folder,hits(ii).name);
end

function str=mmss(seconds)
    seconds=max(0,double(seconds));
    str=sprintf('%02dm %05.2fs',floor(seconds/60),mod(seconds,60));
end

