function report = test_commit_m_preflight()
%TEST_COMMIT_M_PREFLIGHT  Cheap checks without SA/GPS optimization or AMI.
    P=run_commit_m_final_fig7('DryRun',true);
    assert(P.dryRun && P.signature.PatternSearch.UseCompletePoll && ...
        P.signature.nStarts==12 && ...
        P.signature.maxIterSA==4000 && ...
        P.signature.maxEvalsGPS==4001 && ...
        height(P.taskPlan)==24);
    for i=1:12
        assert(norm(P.feasibleStarts(:,i)- ...
            AMI_functions.project_constellation_1D(P.rawStarts(:,i), ...
            build_fso_config(8,1,20,0.3,'minGap',0.01,'pinZero',true)),inf)<1e-12);
        for j=i+1:12
            assert(norm(P.feasibleStarts(:,i)-P.feasibleStarts(:,j),inf)>1e-10);
        end
    end
    assert(isequal(P.taskPlan.Restart(1:12),(1:12)') && ...
        isequal(P.taskPlan.Restart(13:24),(1:12)'));
    assert(all(P.taskPlan.Method(1:12)=="SA") && ...
        all(P.taskPlan.Method(13:24)=="GPS"));
    sample=table([repmat("GPS",12,1);repmat("SA",12,1)], ...
        [(1:12)';(1:12)'],[(1:12)';(1:12)']*0.01, ...
        ones(24,1)*4001, ...
        'VariableNames',{'Method','Restart','ValidatedAMI','FunctionEvaluations'});
    S=commit_m_optimizer_statistics(sample);
    assert(all(abs(S.BestValidatedAMI-0.12)<1e-12) && ...
        all(abs(S.MeanValidatedAMI-0.065)<1e-12) && ...
        all(abs(S.StdValidatedAMI-std((1:12)'*.01,0))<1e-12));
    report=struct('passed',true,'nRestartsPerOptimizer',12, ...
        'nDistinctStarts',12,'useCompletePoll',true,'maxEvals',4001, ...
        'figureUses','maximum validated AMI','varianceUses','all 12');
    disp(report);
end
