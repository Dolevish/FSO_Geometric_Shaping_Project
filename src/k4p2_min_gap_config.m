function K = k4p2_min_gap_config()
%K4P2_MIN_GAP_CONFIG  Commit K.4.2: ONLY the two new d_min=0.001 points.
%
% ALL scientific inputs are copied from the frozen Commit-K profile:
% M=16,32; SNR=20dB; sigma_R^2=0.2; P_avg=1; pinZero;
% 2 paired replicates; 8 restarts and 8000 SA iterations per restart;
% identical production log-h fast evaluator, validator, SA temperature
% schedule and same deterministic (M,replicate) restart seeds.
% Existing d_min=0.005 and all other results are REUSED, not recomputed.

    K=k_min_gap_config();
    K.version='K4p2-v1';
    K.description='K4.2: add d_min=0.001 (M16/M32) without changing K/K4 sources';
    K.MinGapVec=0.001;
    K.MinGapByM={[0.001],[0.001]};
    K.nPhysicalSensitivityPoints=2;
    K.nReplicateCases=4;
    K.nRestartTasks=32;
    K.totalSAIterations=K.nRestartTasks*K.MaxIter;
    K.nominalFastObjectiveEvaluations= ...
        K.nRestartTasks*(K.MaxIter+1);

    assert(isequal(K.MVec,[16 32]) && ...
        K.SNRdB==20 && K.SigmaR2==0.2 && ...
        K.P_avg==1 && K.pinZero && ...
        isequal(K.Replicates,[1 2]) && ...
        K.NStarts==8 && K.MaxIter==8000 && ...
        all(abs(K.SelectedDtByM-0.01)<1e-12) && ...
        K.nRestartTasks==32 && ...
        K.totalSAIterations==256000 && ...
        K.nominalFastObjectiveEvaluations==256032 && ...
        strcmp(K.scheduler,'parfeval-dynamic-v1') && ...
        strcmp(K.FastFadingMethod,'logh') && ...
        strcmp(K.YGridMode,'candidate-adaptive'), ...
        'K4p2:FrozenPolicy','Frozen Commit K scientific protocol changed.');
end
