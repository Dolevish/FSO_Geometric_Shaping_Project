AMI_PAM = zeros(nM, nSig, nSNR);

for iM = 1:nM
    M = M_vec(iM);
    fprintf('  M = %d\n', M);
    
    for iSig = 1:nSig
        sigma_X_sq = sigX_vec(iSig);
        
        for iSNR = 1:nSNR
            SNR_dB = snr_vec(iSNR);
            SNR_lin = 10^(SNR_dB/10);
            
            % Build full cfg structure
            cfg = struct();
            cfg.M          = M;
            cfg.P_avg      = P_avg;
            cfg.SNR_dB     = SNR_dB;
            cfg.sigma_X_sq = sigma_X_sq;
            cfg.sigma_n_sq = P_avg / SNR_lin;
            cfg.R          = 1;
            cfg.sig_t      = sqrt(log(1 + sigma_X_sq));
            cfg.mu_t       = -0.5 * cfg.sig_t^2;
            cfg.ghN_h      = ghN_h;
            cfg.px         = ones(M, 1) / M;
            
            % Get optimized constellation
            x_constellation = x_opt{iM}{iSig, iSNR};
            
            % Compute AMI for OPT
            AMI_OPT(iM, iSig, iSNR) = AMI_functions.AMI_noCSI_validate(...
                x_constellation, cfg.px, cfg);
            
            % Compute AMI for PAM baseline
            x_pam = define_constellation(M, P_avg, 'mean');
            AMI_PAM(iM, iSig, iSNR) = AMI_functions.AMI_noCSI_validate(...
                x_pam, cfg.px, cfg);
        end
    end
end

